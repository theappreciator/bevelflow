import { HttpError } from "./http";

const SAFE_METHODS = new Set(["GET", "HEAD", "OPTIONS"]);

/**
 * Blocks cross-site requests that change data (CSRF). A malicious site can make a
 * signed-in browser send POST/PATCH/DELETE here with the login cookie attached; the
 * browser always says where such a request came from (Origin, or Sec-Fetch-Site), so
 * anything not from this site itself is rejected.
 */
export function assertSameOrigin(request: Request): void {
  if (SAFE_METHODS.has(request.method)) return;
  const origin = request.headers.get("origin");
  if (origin !== null) {
    if (origin === new URL(request.url).origin) return;
    throw new HttpError(403, "Cross-site request blocked");
  }
  // No Origin header: fall back to Fetch Metadata. A missing header means an old or
  // non-browser client, which a signed-in browser attack can't produce, but we still
  // refuse rather than guess.
  if (request.headers.get("sec-fetch-site") === "same-origin") return;
  throw new HttpError(403, "Cross-site request blocked");
}

/**
 * Security headers for responses generated by our Functions (API JSON, photos, the /q/
 * pages). Static files get theirs from public/_headers.
 */
export function withSecurityHeaders(response: Response, csp = "default-src 'none'; frame-ancestors 'none'"): Response {
  const res = new Response(response.body, response);
  res.headers.set("x-content-type-options", "nosniff");
  res.headers.set("x-frame-options", "DENY");
  res.headers.set("referrer-policy", "strict-origin-when-cross-origin");
  if (!res.headers.has("content-security-policy")) res.headers.set("content-security-policy", csp);
  return res;
}
